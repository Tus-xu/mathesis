/** 查文案：查不到时返回 key 本身（显式暴露缺口，不伪造）。 */
export function copyFor(key: string | null | undefined): string {
  if (!key) return ''
  return COPY_ZH_CN[key] ?? key
}

/** 模板插值：`copyFor` + 可选后缀（如「产物 1」）。 */
export function copyWith(key: string, suffix?: string | number | null): string {
  const base = copyFor(key)
  if (suffix === null || suffix === undefined || suffix === '') return base
  return `${base} ${suffix}`
}

/**
 * 位置插值（T24）：把 `{0}` `{1}` 换成实参。
 *
 * 为什么需要它：`copyWith` 只做"基串 + 空格 + 后缀"，无法表达「第 {0} 版」这类
 * 中文语序。缺参时**保留占位符**（显式暴露缺口，而不是悄悄输出空串）。
 */
export function copyFormat(key: string, ...values: Array<string | number>): string {
  const base = copyFor(key)
  return base.replace(/\{(\d+)\}/g, (match, index) => {
    const value = values[Number(index)]
    return value === null || value === undefined ? match : String(value)
  })
}
